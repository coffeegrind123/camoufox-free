#!/usr/bin/env python3
"""
Generate SkNeonEmuShuffle.h: SkNeonEmu.h's interleaving loads and stores
(vld2/3/4, vst2/4) as clang vector shuffles.

    python3 browser/scripts/gen-neon-emu-shuffle.py           # write the header
    python3 browser/scripts/gen-neon-emu-shuffle.py --check   # fail if it is stale

The lane-wise versions in SkNeonEmu.h stay the reference; each one listed here
is replaced by a shuffle that moves the same bytes (browser/tests/neon-emu).
"""

import argparse
import sys
from pathlib import Path

HEADER = (Path(__file__).resolve().parents[1] / "additions" / "gfx" / "skia" / "skia"
          / "src" / "opts" / "SkNeonEmuShuffle.h")

# (intrinsic suffix, element type, lanes per register, registers, NEON type prefix)
# Every interleaving load or store the Skia sources built against SkNeonEmu.h use.
OPS = [
    ("_u8", "uint8_t", 8, 2, "uint8x8"), ("q_u8", "uint8_t", 16, 2, "uint8x16"),
    ("_u8", "uint8_t", 8, 3, "uint8x8"), ("q_u8", "uint8_t", 16, 3, "uint8x16"),
    ("_u8", "uint8_t", 8, 4, "uint8x8"), ("q_u8", "uint8_t", 16, 4, "uint8x16"),
    ("_u16", "uint16_t", 4, 2, "uint16x4"), ("q_u16", "uint16_t", 8, 2, "uint16x8"),
    ("_u16", "uint16_t", 4, 4, "uint16x4"), ("q_u16", "uint16_t", 8, 4, "uint16x8"),
    ("q_f32", "float", 4, 4, "float32x4"),
]


def pow2(x):
    p = 1
    while p < x:
        p *= 2
    return p


def vec_name(t, lanes):
    return f"neon_emu_{t.replace('_t', '')}x{lanes}"


def generate():
    types, funcs = {}, []
    for suf, t, n, k, v in OPS:
        total = n * k
        big = vec_name(t, pow2(total))
        types[big] = (t, pow2(total))
        lanes = "\n".join(
            f"  r.val[{j}] = __builtin_shufflevector(b, b, {', '.join(str(j + i * k) for i in range(n))});"
            for j in range(k))
        # b is zero-filled past the loaded bytes, so a 3-way load reads only its own.
        funcs.append(f"""NEON_EMU_SI {v}x{k}_t neon_emu_shuf_vld{k}{suf}(const {t}* p) {{
  {big} b = {{}};
  memcpy(&b, p, {total} * sizeof({t}));
  {v}x{k}_t r;
{lanes}
  return r;
}}
#define vld{k}{suf} neon_emu_shuf_vld{k}{suf}
""")
        if k == 3:
            continue  # no 3-way store is used, and 3n lanes have no vector type
        pair = ", ".join(str(i) for i in range(2 * n))
        if k == 2:
            cat = f"  {big} c = __builtin_shufflevector(v.val[0], v.val[1], {pair});"
        else:
            half = vec_name(t, 2 * n)
            types[half] = (t, 2 * n)
            quad = ", ".join(str(i) for i in range(4 * n))
            cat = (f"  {half} lo = __builtin_shufflevector(v.val[0], v.val[1], {pair});\n"
                   f"  {half} hi = __builtin_shufflevector(v.val[2], v.val[3], {pair});\n"
                   f"  {big} c = __builtin_shufflevector(lo, hi, {quad});")
        order = ", ".join(str(j * n + i) for i in range(n) for j in range(k))
        funcs.append(f"""NEON_EMU_SI void neon_emu_shuf_vst{k}{suf}({t}* p, {v}x{k}_t v) {{
{cat}
  {big} o = __builtin_shufflevector(c, c, {order});
  memcpy(p, &o, {total} * sizeof({t}));
}}
#define vst{k}{suf} neon_emu_shuf_vst{k}{suf}
""")
    typedefs = "\n".join(f"typedef NEON_EMU_VEC({t}, {lanes}) {name};"
                         for name, (t, lanes) in sorted(types.items()))
    return f"""/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/. */

// SkNeonEmu.h's interleaving loads and stores (vld2/3/4, vst2/4) as clang
// vector shuffles instead of one lane at a time. They move the same bytes;
// browser/tests/neon-emu compares them with the lane-wise versions.
// Generated by browser/scripts/gen-neon-emu-shuffle.py; do not edit.

#ifndef SkNeonEmuShuffle_DEFINED
#define SkNeonEmuShuffle_DEFINED

#if NEON_EMU_SHUFFLE

{typedefs}

{chr(10).join(funcs)}
#endif  // NEON_EMU_SHUFFLE
#endif  // SkNeonEmuShuffle_DEFINED
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the header differs from the generated one")
    args = ap.parse_args()
    text = generate()
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            sys.exit(f"{HEADER} is stale: run {Path(__file__).name}")
        return
    HEADER.write_text(text)


if __name__ == "__main__":
    main()
